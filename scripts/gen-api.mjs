// Generates src/api/schema.d.ts from the backend's OpenAPI schema.
//
// Usage:
//   npm run gen:api                          # VITE_API_URL (Vite env files), else the local backend
//   npm run gen:api -- https://api.example   # a backend origin: fetches <origin>/api/schema/
//   npm run gen:api -- ./schema.json         # a schema file, e.g. the backend repo's committed one
//
// Generate against the backend's `main` (what production runs), not a feature branch.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { loadEnv } from 'vite';

const LOCAL_BACKEND = 'http://127.0.0.1:8000';
const OUTPUT = resolve('src/api/schema.d.ts');

function resolveSource(arg) {
  if (arg && !/^https?:\/\//i.test(arg)) {
    return pathToFileURL(resolve(arg));
  }
  const env = loadEnv(
    process.env.MODE ?? 'development',
    process.cwd(),
    'VITE_',
  );
  const origin = (arg || env.VITE_API_URL || LOCAL_BACKEND).replace(/\/+$/, '');
  return new URL(`${origin}/api/schema/`);
}

const source = resolveSource(process.argv[2]);
console.log(`Generating ${OUTPUT} from ${source.href}`);

try {
  const ast = await openapiTS(source);
  const header =
    '// Generated by `npm run gen:api` (scripts/gen-api.mjs). Do not edit by hand.\n\n';
  await mkdir(dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, header + astToString(ast));
  console.log('Done.');
} catch (error) {
  console.error(`gen:api failed for ${source.href}`);
  console.error(
    'Pass an origin starting with http(s):// or the path of an existing schema file.',
  );
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
